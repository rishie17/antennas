def f(x, nd=2):
    return 'n/a' if x == '' or (isinstance(x, float) and np.isnan(x)) else f'{x:.{nd}f}'


def e(x):
    return f'{x:.1e}'


def load():
    d = {k: read_csv(RES / f'{k}.csv') for k in ('summary_methods', 'complexity', 'specnorm', 'scaling', 'bstar')}
    d['course'] = {(r['method'], r['b']): r for r in select(d['summary_methods'], band='course_5-10GHz')}
    d['full'] = {(r['method'], r['b']): r for r in select(d['summary_methods'], band='full_0.1-1')}
    d['cx'] = {(r['method'], r['N'], r['b']): r for r in d['complexity']}
    d['bstar'] = d['bstar'][0]['b_star']
    d['hw'] = {(int(r['N']), r['method']): r for r in read_csv(RES / 'hardware_table.csv')}
    d['disp'] = {(r['medium'], r['design']): r for r in read_csv(RES / 'dispersion_summary.csv')}
    return d


def headline(d):
    c, cx = d['course'], d['cx']
    spec_advm = col(select(d['specnorm'], method='ADVM'), 'rel_err')
    return dict(
        ps_spread=c[('PS', '')]['squint_spread_deg'], ex_spread=c[('EXACT', '')]['squint_spread_deg'],
        adv_spread=c[('ADVM', '')]['squint_spread_deg'],
        ps_perr=c[('PS', '')]['max_point_err_deg'], ex_perr=c[('EXACT', '')]['max_point_err_deg'],
        adv_perr=c[('ADVM', '')]['max_point_err_deg'],
        ex_sll=c[('EXACT', '')]['worst_sll_db'], adv_sll=c[('ADVM', '')]['worst_sll_db'],
        adv_dsll=c[('ADVM', '')]['worst_sll_delta_db'], adv_gvar=c[('ADVM', '')]['max_gain_var_db'],
        adv_dsll_full=d['full'][('ADVM', '')]['worst_sll_delta_db'],
        spec_min=spec_advm.min(), spec_max=spec_advm.max(),
        r16_dir=cx[('ADVM', 16, '')]['red_vs_direct_pct'], r16_ex=cx[('ADVM', 16, '')]['red_vs_exact_pct'],
        r1024_dir=cx[('ADVM', 1024, '')]['red_vs_direct_pct'], r1024_ex=cx[('ADVM', 1024, '')]['red_vs_exact_pct'],
    )


METHOD_ROWS = [('PS', ''), ('EXACT', ''), ('ADVM', '')] + [('ADVM-b', b) for b in B_SWEEP]


def label(m, b):
    return f'ADVM-b (b={int(b)})' if m == 'ADVM-b' else m


def methods_table_rows(d):
    rows = []
    for m, b in METHOD_ROWS:
        r = d['course'][(m, float(b) if b != '' else '')]
        gd = d['cx'][(m, N_MAIN, float(b) if b != '' else '')]['gain_delay'] if m != 'PS' else None
        rows.append((label(m, b), f(r['squint_spread_deg']), f(r['max_point_err_deg']), f(r['max_gain_var_db']),
                     f(r['worst_sll_db']), f(r['worst_sll_delta_db']), 'n/a' if gd is None else f'{int(gd)}',
                     'yes' if r['meets_criteria'] else 'no'))
    return rows


